"""Benchmark ARTActivationDetector vs a linear probe on SYNTHETIC activations.

The data are Gaussian clusters generated by this script (no model is involved):
"backdoored" samples are clean noise shifted by a constant in every dimension.
The numbers therefore only compare how the two detectors behave on this toy
distribution; they are not measurements of backdoor detection on a real model.

Protocol:
- separate, seeded training and held-out sets;
- detectors are fit on the training set and AUC is reported on the held-out set
  (training AUC is in-sample and shown only for the train/test gap);
- the TPR/FPR/F1 decision threshold (Youden's J) is chosen on the training set
  and applied unchanged to the held-out set;
- the supervised linear probe is also trained on shuffled labels as a chance
  control. ARTActivationDetector is unsupervised (it does not use the labels).
"""

from pathlib import Path
import sys
import time
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from probe_eval_utils import (  # noqa: E402
    DEFAULT_SEED,
    LinearProbeDetector,
    evaluate_heldout,
    shuffled_label_auc,
)

from sleeper_agents.detection.art_activation_detector import ARTActivationDetector  # noqa: E402
from sleeper_agents.detection.base_detector import BaseDetector  # noqa: E402


def generate_backdoor_dataset(
    n_clean: int = 500,
    n_backdoor: int = 100,
    hidden_dim: int = 768,
    seq_len: int = 20,
    separation: float = 3.0,
    noise_level: float = 1.0,
    seed: int = DEFAULT_SEED,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Generate synthetic "clean" and "backdoored" activation clusters.

    Args:
        n_clean: Number of clean training samples
        n_backdoor: Number of shifted training samples
        hidden_dim: Activation dimension
        seq_len: Sequence length
        separation: Constant added to every dimension of the shifted cluster
        noise_level: Standard deviation of the noise
        seed: Random seed

    Returns:
        X_train, y_train, X_test, y_test (held-out set is 30% of the training size,
        drawn independently from the same distributions)
    """
    rng = np.random.default_rng(seed)

    def draw(n: int, shift: float) -> np.ndarray:
        return (rng.standard_normal((n, seq_len, hidden_dim)) * noise_level + shift).astype(np.float32)

    X_train = np.vstack([draw(n_clean, 0.0), draw(n_backdoor, separation)])
    y_train = np.array([0] * n_clean + [1] * n_backdoor)

    n_clean_test = int(n_clean * 0.3)
    n_backdoor_test = int(n_backdoor * 0.3)
    X_test = np.vstack([draw(n_clean_test, 0.0), draw(n_backdoor_test, separation)])
    y_test = np.array([0] * n_clean_test + [1] * n_backdoor_test)

    train_idx = rng.permutation(len(X_train))
    test_idx = rng.permutation(len(X_test))
    return X_train[train_idx], y_train[train_idx], X_test[test_idx], y_test[test_idx]


def benchmark_detector(
    detector: BaseDetector,
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_test: np.ndarray,
    y_test: np.ndarray,
    shuffled_control: bool = False,
    seed: int = DEFAULT_SEED,
) -> Dict[str, Any]:
    """Fit on the training set, evaluate on the held-out set.

    Args:
        detector: Detector to benchmark
        X_train, y_train: Training activations and labels
        X_test, y_test: Held-out activations and labels
        shuffled_control: Also report the label-shuffled AUC (supervised detectors)
        seed: Seed for the shuffled-label control

    Returns:
        Held-out metrics (threshold chosen on the training set), timing and controls
    """
    train_start = time.time()
    detector.fit(X_train, y_train)
    train_time = time.time() - train_start

    test_start = time.time()
    test_scores = detector.score(X_test)
    test_time = time.time() - test_start

    metrics = evaluate_heldout(y_train, detector.score(X_train), y_test, test_scores)
    shuffled: Optional[float] = None
    if shuffled_control:
        detector_cls = type(detector)
        shuffled = shuffled_label_auc(lambda: detector_cls(seed=seed), X_train, y_train, X_test, y_test, seed=seed)

    return {
        "detector_name": detector.name,
        "metrics": metrics,
        "shuffled_label_auc": shuffled,
        "timing": {
            "train_time": train_time,
            "test_time": test_time,
            "throughput": len(X_test) / test_time if test_time > 0 else float("inf"),
        },
    }


def print_benchmark_results(results: List[Dict[str, Any]]) -> None:
    """Print held-out results for each detector."""
    print("\n" + "=" * 80)
    print("DETECTOR BENCHMARK RESULTS (synthetic Gaussian clusters)")
    print("=" * 80)

    for result in results:
        m = result["metrics"]
        print(f"\n{result['detector_name']}")
        print("-" * 80)
        print("Held-out set (threshold chosen on the training set):")
        print(f"  AUC-ROC:             {m['auc']:.4f}")
        print(f"  True Positive Rate:  {m['tpr']:.4f}")
        print(f"  False Positive Rate: {m['fpr']:.4f}")
        print(f"  Precision:           {m['precision']:.4f}")
        print(f"  F1 Score:            {m['f1']:.4f}")
        print(f"Training set AUC (in-sample): {m['train_auc']:.4f}  (gap {abs(m['train_auc'] - m['auc']):.4f})")
        if result["shuffled_label_auc"] is not None:
            print(f"Shuffled-label control AUC:   {result['shuffled_label_auc']:.4f}  (chance ~0.5)")
        timing = result["timing"]
        print(f"Timing: train {timing['train_time']:.4f}s, inference {timing['test_time']:.4f}s")

    print("\nNote: synthetic data with a large, uniform shift; results do not transfer to real models.")


def main():
    """Run detector benchmark."""
    print("\n" + "=" * 80)
    print("DETECTOR BENCHMARK: ARTActivationDetector vs Linear Probe (synthetic data)")
    print("=" * 80)

    print("\n[1/3] Generating synthetic activation clusters...")
    X_train, y_train, X_test, y_test = generate_backdoor_dataset(seed=DEFAULT_SEED)
    print(f"  Training set: {len(X_train)} samples ({np.sum(y_train == 1)} shifted)")
    print(f"  Held-out set: {len(X_test)} samples ({np.sum(y_test == 1)} shifted)")
    print(f"  Activation shape: {X_train.shape}")

    print("\n[2/3] Running benchmarks...")
    results = [
        benchmark_detector(
            ARTActivationDetector(nb_clusters=2, nb_dims=10, pooling_method="mean", normalize=True),
            X_train,
            y_train,
            X_test,
            y_test,
        ),
        benchmark_detector(LinearProbeDetector(), X_train, y_train, X_test, y_test, shuffled_control=True),
    ]

    print("\n[3/3] Results:")
    print_benchmark_results(results)


if __name__ == "__main__":
    main()
